function mediaKey(value) {
  try {
    const url = new URL(value);
    url.hash = ''; // Fragments do not identify a different downloaded media file.
    return url.href;
  } catch { return value; }
}

const ids = new Set(EXCLUDED_WORKS.map(work => work.id));
const mediaUrls = new Set(EXCLUDED_WORKS.flatMap(work => [work.mediaUrl, work.alternateMediaUrl]).filter(Boolean).map(mediaKey));

export function isExcludedWork(work) {
  return Boolean(work && (ids.has(work.id) || mediaUrls.has(mediaKey(work.mediaUrl)) || mediaUrls.has(mediaKey(work.alternateMediaUrl))));
}

export function excludeWorks(works) {
  return works.filter(work => !isExcludedWork(work));
}
